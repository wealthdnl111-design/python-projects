# Slicing a list item

numbers = [10, 20, 30, 40, 50]
print(numbers[:3])

# Using 'insert' method in list collection

fruits = ["Apples", "Banana", "Mango"]
fruits.insert(1, "Orange")
print(fruits)

more_fruits = ["Kiwi", "Jackfruit", "Cherry"]
fruits.extend(more_fruits)
fruits.clear()
print(fruits)

