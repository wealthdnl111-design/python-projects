# Practical exercises using slicing method

fruits = ['Apple', 'Banana', 'Mango', 'Orange', 'Grape', 'Watermelon']

# Numbers [:] (This prints every item in the list.)
print(fruits[:])

# Numbers[:3] (This prints the first three items on the list.)
print(fruits[:3])

# Numbers[2:] (This prints from index 2 to the end.)
print(fruits[2:])

# Numbers[1:4] (This prints from index 1, 2, and 3. Excluding 4.)
print(fruits[1:4])

# Numbers[-2:] (This prints the last to items on the list.)
print(fruits[-2:])

# Numbers[:-1] (This prints every item on the list, except the last.)
print(fruits[:-1])

# Numbers[::2] (This prints every second item in the list)
print(fruits[::2])

# Numbers[::-1] (This reverses the item list)
print(fruits[::-1])